/**
 * Network edit operations (ADR-0010) as sent to the backend. The JSON shape mirrors
 * `TrafficSim.Domain.Editing.EditOperation` (discriminator `op`, which must come first). Edits address
 * OSM elements by id; user-created elements use negative ids chosen by the client.
 */

/** Tag changes: a string sets the tag, `null` removes it. */
export type TagChanges = Record<string, string | null>;

export interface SetWayTagsOp {
  op: 'set_way_tags';
  wayId: number;
  fromNode: number | null;
  toNode: number | null;
  tags: TagChanges;
}

export interface SetNodeTagsOp {
  op: 'set_node_tags';
  nodeId: number;
  tags: TagChanges;
}

/** A node of a new way: an existing node (id only) or a new one (negative id with position). */
export interface WayNodeRef {
  id: number;
  lat?: number;
  lon?: number;
}

export interface AddWayOp {
  op: 'add_way';
  wayId: number;
  nodes: WayNodeRef[];
  tags: Record<string, string>;
}

export interface InsertNodeOp {
  op: 'insert_node';
  wayId: number;
  afterNode: number;
  nodeId: number;
  lat: number;
  lon: number;
}

export interface RemoveWayOp {
  op: 'remove_way';
  wayId: number;
  fromNode: number | null;
  toNode: number | null;
}

export interface ConvertToRoundaboutOp {
  op: 'convert_to_roundabout';
  nodeId: number;
  radius: number;
}

export interface SetLaneConnectionsOp {
  op: 'set_lane_connections';
  nodeId: number;
  fromNeighbour: number;
  fromLane: number;
  toNeighbour: number;
  toLanes: number[];
}

export interface BanMovementOp {
  op: 'ban_movement';
  nodeId: number;
  fromNeighbour: number;
  toNeighbour: number;
}

export interface SetSignalPlanOp {
  op: 'set_signal_plan';
  nodeId: number;
  cycle: number;
  offset: number;
  phaseGreen: number[];
  /** Phase index per approach, keyed by the approach's neighbour OSM node id. */
  approachPhase: Record<string, number> | null;
}

export type EditOperation =
  | SetWayTagsOp
  | SetNodeTagsOp
  | AddWayOp
  | InsertNodeOp
  | RemoveWayOp
  | ConvertToRoundaboutOp
  | SetLaneConnectionsOp
  | BanMovementOp
  | SetSignalPlanOp;

export type Changeset = readonly EditOperation[];

export const OP_NAMES = [
  'set_way_tags',
  'set_node_tags',
  'add_way',
  'insert_node',
  'remove_way',
  'convert_to_roundabout',
  'set_lane_connections',
  'ban_movement',
  'set_signal_plan',
] as const satisfies readonly EditOperation['op'][];

/** A labelled group of operations produced by one user action (one undo step). */
export interface EditResult {
  label: string;
  ops: EditOperation[];
}

/** A user action that cannot be expressed as an edit (shown to the user, nothing is changed). */
export class EditError extends Error {
  constructor(message: string) {
    super(message);
    this.name = 'EditError';
  }
}

/** Ids at or below this value are generated by the backend when it splits ways (never client-chosen). */
export const GENERATED_ID_LIMIT = -1_000_000_000;

function negativeIds(op: EditOperation): number[] {
  switch (op.op) {
    case 'add_way':
      return [op.wayId, ...op.nodes.map((n) => n.id)];
    case 'insert_node':
      return [op.wayId, op.afterNode, op.nodeId];
    case 'set_way_tags':
    case 'remove_way':
      return [op.wayId, op.fromNode ?? 0, op.toNode ?? 0];
    case 'set_node_tags':
    case 'convert_to_roundabout':
    case 'set_signal_plan':
      return [op.nodeId];
    case 'set_lane_connections':
    case 'ban_movement':
      return [op.nodeId, op.fromNeighbour, op.toNeighbour];
  }
}

/** Allocates fresh client ids (negative, unique within the changeset, above the generated range). */
export class IdAllocator {
  private next: number;

  constructor(changeset: Changeset, extra: readonly number[] = []) {
    let min = 0;
    for (const id of [...changeset.flatMap(negativeIds), ...extra]) {
      if (id < min && id > GENERATED_ID_LIMIT) min = id;
    }
    this.next = min - 1;
  }

  take(): number {
    return this.next--;
  }
}

/** Does this op split or remove (part of) the way, so that the way id no longer covers the whole road? */
export function splitsWay(op: EditOperation, wayId: number): boolean {
  if ((op.op === 'set_way_tags' || op.op === 'remove_way') && op.wayId === wayId) {
    return op.fromNode !== null || op.toNode !== null || op.op === 'remove_way';
  }
  return op.op === 'convert_to_roundabout';
}

const tagList = (tags: TagChanges | Record<string, string>) =>
  Object.entries(tags)
    .map(([k, v]) => (v === null ? `−${k}` : `${k}=${v}`))
    .join(', ');

/** Short human-readable description (history and issue lists). */
export function describeOp(op: EditOperation): string {
  switch (op.op) {
    case 'set_way_tags':
      return `Way ${op.wayId}${op.fromNode !== null || op.toNode !== null ? ` (${op.fromNode ?? '…'}–${op.toNode ?? '…'})` : ''}: ${tagList(op.tags)}`;
    case 'set_node_tags':
      return `Node ${op.nodeId}: ${tagList(op.tags)}`;
    case 'add_way':
      return `New road (${op.nodes.length} nodes, ${op.tags.highway ?? 'road'})`;
    case 'insert_node':
      return `Attach point on way ${op.wayId}`;
    case 'remove_way':
      return `Remove way ${op.wayId}${op.fromNode !== null || op.toNode !== null ? ' (part)' : ''}`;
    case 'convert_to_roundabout':
      return `Roundabout at node ${op.nodeId} (r = ${op.radius} m)`;
    case 'set_lane_connections':
      return `Lane connections at node ${op.nodeId}: lane ${op.fromLane} → [${op.toLanes.join(', ')}]`;
    case 'ban_movement':
      return `Ban turn at node ${op.nodeId}`;
    case 'set_signal_plan':
      return `Signal plan at node ${op.nodeId}: cycle ${op.cycle} s, ${op.phaseGreen.length} phases`;
  }
}

/** Light structural check of a changeset received from the server. Unknown ops are rejected. */
export function parseChangeset(input: unknown): EditOperation[] {
  if (!Array.isArray(input)) return [];
  return input.filter(
    (op): op is EditOperation =>
      typeof op === 'object' && op !== null && (OP_NAMES as readonly string[]).includes((op as { op?: unknown }).op as string),
  );
}
